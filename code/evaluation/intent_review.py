"""Intent acceptance: rules vs model on every unique request text (samples + evaluation).

Prints the confusion between the rules and the model's atomic answers, every text either side calls
non-deletion (with the model rationale), and every disagreement with how ADR 0008 resolves it;
writes the disagreement file code/evaluation/intent_disagreements.md (text hashes and rationales
only). Live calls happen only for cache misses and only with OPENAI_API_KEY set; verdicts go to the
cache module.
"""

import hashlib
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "intent_disagreements.md"


def _natural(c):
    return (len(c), c)


def _review_rows(clf, by_text, classify_rules, rules_clarity):
    """(confusion, rows) where each row is (text, cases, rules, model verdict, final, clarity)."""
    conf, rows = Counter(), []
    for text in sorted(by_text):
        r = classify_rules(text)
        v = clf.review(text)
        final = clf.classify(text)
        conf[(r.label, v["label"] if v else "NO_VERDICT")] += 1
        rows.append((text, by_text[text], r, v, final, rules_clarity(text)))
    return conf, rows


def _print_confusion(conf):
    print("CONFUSION (rows = rules, columns = model)")
    for rl in ("DELETION", "NOT_DELETION"):
        print(
            f"  rules {rl:13} -> model DELETION {conf[(rl, 'DELETION')]:4}   model NOT_DELETION "
            f"{conf[(rl, 'NOT_DELETION')]:4}"
            f"   no verdict {conf[(rl, 'NO_VERDICT')]:3}"
        )


def _print_non_deletion(rows):
    print("NON-DELETION BY EITHER SIDE (final decision, source, cases, model rationale)")
    for text, cases, r, v, final, clarity in rows:
        if r.label == "NOT_DELETION" or (v and v["label"] == "NOT_DELETION"):
            print(
                f"  [{final.label} via {final.source}; rules {clarity}] "
                f"{', '.join(sorted(cases, key=_natural))}"
            )
            print(f"      text: {text[:140]}")
            print(f"      model: {v['answers'] if v else None}")


def _write_disagreements(dis):
    """Print the disagreements and write them (hashes, never text) to intent_disagreements.md."""
    lines = [
        "# Intent disagreements, rules vs model (generated by `python3 code/evaluation/main.py "
        "intent`)",
        "",
        "Resolution (ADR 0008): when the rules are clear (only deletion cues, or only "
        "negation/scope cues), the rules decide; "
        "otherwise the model's atomic answers decide.",
        "",
        "| text sha256 (16) | cases | rules | model | rules clarity | final | model rationale |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for text, cases, r, v, final, clarity in dis:
        h = hashlib.sha256(text.encode()).hexdigest()[:16]
        print(
            f"  {h} rules={r.label} ({clarity}) model={v['label']} -> final {final.label} via "
            f"{final.source}: {v['answers']['rationale']}"
        )
        print(f"      text: {text[:140]}")
        lines.append(
            f"| {h} | {len(cases)} | {r.label} | {v['label']} | {clarity} | {final.label} "
            f"({final.source}) | {v['answers']['rationale']} |"
        )
    if not dis:
        lines.append("| (none) | | | | | | |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def run(root=ROOT):
    """`main.py intent`: rules vs model on every unique request text of both request files.

    Writes code/evaluation/intent_disagreements.md and prints the confusion table; live calls
    happen only for cache misses with OPENAI_API_KEY set."""
    sys.path.insert(0, str(root / "code"))
    from ghostaudit import data, llm_intent, usage
    from ghostaudit.intent import classify_rules

    d = root / "dataset"
    reqs = [
        q
        for f in ("sample_deletion_requests.csv", "deletion_requests.csv")
        for q in data.load_requests(d / f)
    ]
    by_text = {}
    for q in reqs:
        by_text.setdefault(q["request_text"], []).append(q["case_id"])
    tracker = usage.Tracker()
    clf = llm_intent.IntentClassifier(client=llm_intent.default_client(), tracker=tracker)
    print(f"prefetch: {clf.prefetch(by_text)} live call(s) for cache misses")
    conf, rows = _review_rows(clf, by_text, classify_rules, llm_intent.rules_clarity)
    clf.save()
    print(f"INTENT REVIEW: {len(by_text)} unique texts over {len(reqs)} requests")
    print(tracker.summary())
    _print_confusion(conf)
    _print_non_deletion(rows)
    dis = [x for x in rows if x[3] and x[3]["label"] != x[2].label]
    print(f"DISAGREEMENTS rules vs model: {len(dis)}")
    _write_disagreements(dis)
    na = sorted(
        {c for text, cases, r, v, final, _ in rows if final.label == "NOT_DELETION" for c in cases},
        key=_natural,
    )
    print(f"FINAL NOT_DELETION cases: {len(na)}: {', '.join(na)}")
    return 0
