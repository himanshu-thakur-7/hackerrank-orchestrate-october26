"""Usage report generator: final_run() measures the full-dataset run, render(data) writes the
Markdown.

  python3 code/evaluation/main.py usage    -> code/evaluation/usage_report.md

final_run() runs code/main.py on all 518 requests into a temp file with --usage-json and checks that
its output is byte-identical to the committed output.csv, so the report describes the run that
produced it. Cache origins come from the ORIGIN records inside the generated cache modules (calls
and tokens only).

Decisions: ADR 0008 (cached intent calls), ADR 0013 (Jev usage is evaluation-only).
"""

import hashlib
import json
import os
import subprocess
import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "dataset"
OUT = Path(__file__).resolve().parent / "usage_report.md"


def final_run(data_dir=DATA, env=None):
    """Run code/main.py on all requests with --usage-json and return its usage summary.

    The summary also holds the output's sha256, whether it is byte-identical to the committed
    output.csv, and whether a key was set. Raises RuntimeError when the run fails."""
    tmp = Path(tempfile.mkdtemp(prefix="ghostaudit_usage_"))
    p = subprocess.run(
        [
            sys.executable,
            str(ROOT / "code" / "main.py"),
            "--data",
            str(data_dir),
            "--out",
            str(tmp / "output.csv"),
            "--usage-json",
            str(tmp / "usage.json"),
        ],
        capture_output=True,
        text=True,
        cwd=ROOT,
        env=os.environ.copy() if env is None else env,
    )
    if p.returncode != 0:
        raise RuntimeError(f"final run failed: {p.stderr[-2000:]}")
    u = json.loads((tmp / "usage.json").read_text(encoding="utf-8"))
    sha = hashlib.sha256((tmp / "output.csv").read_bytes()).hexdigest()
    committed = ROOT / "output.csv"
    u.update(
        sha256=sha,
        output_matches=committed.exists()
        and hashlib.sha256(committed.read_bytes()).hexdigest() == sha,
        key_set=bool((os.environ if env is None else env).get("OPENAI_API_KEY")),
    )
    return u


def collect(env=None):
    """Every number of the usage report: the measured run, cache origins and entry counts."""
    sys.path.insert(0, str(ROOT / "code"))
    from ghostaudit import llm_intent

    from evaluation import jev_ranker

    commit = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=ROOT
    ).stdout.strip()
    return {
        "generated_at": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "commit": commit or "unknown",
        "final": final_run(env=env),
        "openai_origin": llm_intent.read_origin(),
        "openai_cache_entries": len(llm_intent.read_cache()),
        "jev_origin": jev_ranker.read_origin(),
        "jev_cache_entries": len(jev_ranker.read_cache()),
    }


def _cost(model, tin, tout):
    from ghostaudit.usage import PRICE_PER_MTOK

    p_in, p_out = PRICE_PER_MTOK.get(model, (0.0, 0.0))
    return (tin * p_in + tout * p_out) / 1e6


def render(d):
    """The usage report Markdown for `d` (as returned by collect)."""
    sys.path.insert(0, str(ROOT / "code"))
    from ghostaudit.llm_intent import MODEL as OPENAI
    from ghostaudit.usage import PRICE_PER_MTOK

    from evaluation.jev_ranker import MODEL as JEV
    from evaluation.jev_ranker import PRICE_IN_PER_MTOK as JEV_IN

    f, t = d["final"], d["final"]["totals"]
    n = f["requests"]
    L = [
        "# Usage report",
        "",
        f"Generated by `python3 code/evaluation/main.py usage` at {d['generated_at']} (commit "
        f"`{d['commit']}`). Every number is "
        "measured at generation time or read from the ORIGIN records of the generated cache "
        "modules; nothing is typed by hand.",
        "",
        "## 1. Final full-dataset run (the run that produced output.csv)",
        "",
        f"- Command: `python3 code/main.py` over all **{n}** requests in "
        f"`dataset/deletion_requests.csv`.",
        f"- Its output sha256 is `{f['sha256'][:12]}`, which is "
        + (
            "**byte-identical to the committed output.csv**."
            if f["output_matches"]
            else "**NOT identical to the committed output.csv**."
        ),
        f"- `OPENAI_API_KEY` was {'set' if f['key_set'] else 'not set'} in the environment for "
        f"this run. The key's value is never read by our code, printed or stored.",
        "- Intent is the only model use in the solver (ADR 0008). Rules decide clear texts; the "
        "model decides only texts where deletion and "
        "negation/scope cues both fire. Its verdicts are served from the committed cache when "
        "present.",
        "",
    ]
    if f.get("intent"):
        c = f["intent"]
        L += [
            f"Intent decisions per unique request text: rules (clear) {c['rules']}, cache "
            f"{c['cache']}, live model {c['model']}, "
            f"rules fallback {c['rules_fallback']}, degraded by error {c['degraded']}.",
            "",
        ]
    L += [
        "| provider | model | live calls | cache hits | input tokens | output tokens | avg tokens "
        "per live call | tokens per request | est. cost | cost per request | degraded by error |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    models = sorted(set(t["per_model"]) | set(t.get("cache_hits_per_model", {})) | {OPENAI})
    for m in models:
        pm = t["per_model"].get(
            m, {"provider": "openai", "calls": 0, "input_tokens": 0, "output_tokens": 0}
        )
        tok = pm["input_tokens"] + pm["output_tokens"]
        cost = _cost(m, pm["input_tokens"], pm["output_tokens"])
        L.append(
            f"| {pm['provider']} | {m} | {pm['calls']} | "
            f"{t.get('cache_hits_per_model', {}).get(m, 0)} | {pm['input_tokens']:,} | "
            f"{pm['output_tokens']:,} | {tok / pm['calls'] if pm['calls'] else 0:.0f} | "
            f"{tok / n:.1f} | ${cost:.4f} | ${cost / n:.6f} | {t['degraded']} |"
        )
    tok = t["input_tokens"] + t["output_tokens"]
    L += [
        f"| **overall** | | {t['calls']} | {t['cache_hits']} | {t['input_tokens']:,} | "
        f"{t['output_tokens']:,} | "
        f"{tok / t['calls'] if t['calls'] else 0:.0f} | {tok / n:.1f} | ${t['cost_usd']:.4f} | "
        f"${t['cost_usd'] / n:.6f} | {t['degraded']} |",
        "",
    ]
    L += [
        f"- Cache hits cost 0 tokens. The run's degraded-by-error count is {t['degraded']} "
        f"({t['failed_attempts']} failed attempts)."
    ]
    L += [f"- Note: {x}" for x in t.get("notes", [])]
    L += [
        "",
        "## 2. Where the cache came from (origin of the committed intent verdicts)",
        "",
        f"`code/ghostaudit/llm_cache.py` holds {d['openai_cache_entries']} entries (keys are "
        f"sha256 of model + prompt + text; values are answers only). "
        "These runs made the live calls that added them:",
        "",
        "| run | live calls | entries added | input tokens | output tokens | est. cost |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    oi = oo = oc = 0
    for r in d["openai_origin"]:
        c = _cost(OPENAI, r["input_tokens"], r["output_tokens"])
        oi += r["input_tokens"]
        oo += r["output_tokens"]
        oc += r["live_calls"]
        L.append(
            f"| {r['run_at']} | {r['live_calls']} | {r['entries_added']} | {r['input_tokens']:,} | "
            f"{r['output_tokens']:,} | ${c:.4f} |"
        )
    ocost = _cost(OPENAI, oi, oo)
    L += [
        f"| **total** | {oc} | | {oi:,} | {oo:,} | ${ocost:.4f} |",
        "",
        f"- The origin review classified every unique request text (eval and sample) with the "
        f"model, to measure rules/model disagreement. "
        f"Amortized over the {n} eval requests, that is {(oi + oo) / n:.1f} tokens and "
        f"${ocost / n:.6f} per request.",
        f"- With an empty cache and a key, the solver run would call the model only for the "
        f"remainder texts "
        f"({(f.get('intent') or {}).get('cache', 0)} unique texts, {t['cache_hits']} requests); "
        f"today these are the cache hits of section 1.",
        "",
        "## 3. Evaluation-only model: TypeSafe Jev",
        "",
        f"- Jev (`{JEV}`, `typesafe-sdk`) is used **evaluation only**, by `python3 "
        f"code/evaluation/main.py jev-rank`. It writes an advisory review "
        "queue (`docs/JEV_REVIEW_QUEUE.md`). It is never imported by `code/main.py` and has no "
        "effect on output.csv.",
        "- The key is read by the SDK from `TYPESAFE_API_KEY` in the environment only.",
    ]
    jo, jcost = d.get("jev_origin"), 0.0
    if jo:
        jcost = jo["input_tokens"] * JEV_IN / 1e6
        L += [
            f"- `code/evaluation/jev_cache.py` holds {d['jev_cache_entries']} entries (mean of 10 "
            f"calls per cited step). "
            f"The run that produced it ({jo['run_at']}) made:",
            "",
            "| provider | model | live calls | call errors | input tokens | output tokens | avg "
            "tokens per call | est. cost |",
            "| --- | --- | --- | --- | --- | --- | --- | --- |",
            f"| typesafe | {JEV} | {jo['live_calls']:,} | {jo['errors']} | {jo['input_tokens']:,} "
            f"| {jo['output_tokens']:,} | "
            f"{(jo['input_tokens'] + jo['output_tokens']) / jo['live_calls']:.0f} | ${jcost:.4f} |",
            "",
            "- A rerun with no key reads the cache and makes 0 calls.",
        ]
    else:
        L += ["- No Jev run is recorded in the cache."]
    L += [
        "",
        "## 4. Totals per model and overall",
        "",
        "| provider | model | role | live calls (all recorded runs) | input tokens | output tokens "
        "| est. cost |",
        "| --- | --- | --- | --- | --- | --- | --- |",
        f"| openai | {OPENAI} | solver intent (cache origin + final run) | {oc + t['calls']:,} | "
        f"{oi + t['input_tokens']:,} | {oo + t['output_tokens']:,} | ${ocost + t['cost_usd']:.4f} "
        f"|",
    ]
    if jo:
        L.append(
            f"| typesafe | {JEV} | evaluation only | {jo['live_calls']:,} | {jo['input_tokens']:,} "
            f"| {jo['output_tokens']:,} | ${jcost:.4f} |"
        )
    ji, jout, jc = (jo["input_tokens"], jo["output_tokens"], jo["live_calls"]) if jo else (0, 0, 0)
    L += [
        f"| **overall** | | | {oc + t['calls'] + jc:,} | {oi + t['input_tokens'] + ji:,} | "
        f"{oo + t['output_tokens'] + jout:,} | "
        f"${ocost + t['cost_usd'] + jcost:.4f} |",
        "",
        "## 5. Prices and assumptions",
        "",
        f"- `{OPENAI}`: ${PRICE_PER_MTOK[OPENAI][0]} / 1M input, ${PRICE_PER_MTOK[OPENAI][1]} / 1M "
        f"output (provider model page, checked 2026-10-25).",
        f"- `{JEV}`: ${JEV_IN} / 1M input, output free (aggregator listings; no TypeSafe price "
        f"table found). Indicative only.",
        "- Costs are estimates from token counts reported by the APIs. Spike runs "
        "(`docs/JEV_SPIKE.md`) are reported there, not here.",
        "- Environment variables, by name only: `OPENAI_API_KEY` (optional, intent), "
        "`TYPESAFE_API_KEY` (optional, evaluation only).",
        "",
        "## 6. Reproduce",
        "",
        "```text",
        "python3 code/main.py                       # output.csv; 0 live calls with the committed "
        "cache",
        "python3 code/evaluation/main.py usage      # regenerates this report",
        "```",
        "",
    ]
    return "\n".join(L)


def run(out=OUT):
    """`main.py usage`: collect, write usage_report.md, print a summary; returns the data."""
    d = collect()
    Path(out).write_text(render(d), encoding="utf-8")
    t = d["final"]["totals"]
    print(
        f"usage report: final run {d['final']['requests']} requests, live calls {t['calls']}, "
        f"cache hits {t['cache_hits']}, "
        f"output matches committed output.csv: {d['final']['output_matches']} -> {out}"
    )
    return d
