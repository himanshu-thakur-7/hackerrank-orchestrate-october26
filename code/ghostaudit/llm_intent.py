"""Intent: rules pre-screen, cached model for the remainder (ADR 0008).

  IntentClassifier(client, cache, tracker).classify(text) -> Intent(label, reason, source)
  .review(text)  -> model verdict for any text (evaluation: rules vs model confusion); disagreements recorded

Decision:
  * clear rules case: a deletion cue and no negation/scope cue (DELETION), or a negation/scope cue and no
    deletion cue (NOT_DELETION) -> rules decide;
  * remainder (both cues, or neither) -> the model's atomic yes/no answers decide:
      DELETION iff (asks_to_delete or asks_to_verify_or_finish_deletion) and not excludes_deletion;
  * no model verdict available (no key and no cache entry) -> the rules label, marked as such.
Model verdicts come from the committed cache first (code/ghostaudit/llm_cache.py, keyed by
sha256(model + prompt + text)); a live call happens only on a cache miss with OPENAI_API_KEY set.
The key is read by the SDK from the environment and never touched here.
"""
import hashlib
import importlib.util
import json
import os
import time
from pathlib import Path

from ghostaudit.intent import Intent, _del, _neg, classify_rules

MODEL = "gpt-5.4-mini-2026-03-17"
SEED = 20261025
PROMPT_PATH = Path(__file__).resolve().parents[1] / "prompts" / "intent_classifier.md"
CACHE_PATH = Path(__file__).resolve().parent / "llm_cache.py"
SCHEMA = {
    "name": "intent_answers", "strict": True,
    "schema": {"type": "object", "additionalProperties": False,
               "required": ["asks_to_delete", "asks_to_verify_or_finish_deletion", "excludes_deletion", "rationale"],
               "properties": {"asks_to_delete": {"type": "boolean"}, "asks_to_verify_or_finish_deletion": {"type": "boolean"},
                              "excludes_deletion": {"type": "boolean"}, "rationale": {"type": "string"}}},
}


def prompt_text():
    return PROMPT_PATH.read_text(encoding="utf-8")


def cache_key(text, prompt=None, model=MODEL):
    return hashlib.sha256(f"{model}\n{prompt if prompt is not None else prompt_text()}\n{text}".encode("utf-8")).hexdigest()


def build_messages(text, prompt=None):
    safe = (text or "").replace("MESSAGE>>>", "MESSAGE> > >").replace("<<<MESSAGE", "< < <MESSAGE")
    return [{"role": "system", "content": prompt if prompt is not None else prompt_text()},
            {"role": "user", "content": f"<<<MESSAGE\n{safe}\nMESSAGE>>>"}]


def label(answers):
    asks = answers["asks_to_delete"] or answers["asks_to_verify_or_finish_deletion"]
    return "DELETION" if asks and not answers["excludes_deletion"] else "NOT_DELETION"


def rules_clarity(text):
    """'clear' when the rules' cues point one way only; 'remainder' when both or neither fire."""
    de, neg = any(p.search(text) for p in _del), any(p.search(text) for p in _neg)
    return "clear" if de != neg else "remainder"


def read_cache(path=CACHE_PATH):
    if not Path(path).exists():
        return {}
    spec = importlib.util.spec_from_file_location("ghostaudit_llm_cache", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return dict(mod.CACHE)


def write_cache(path, cache):
    lines = ['"""GENERATED by ghostaudit.llm_intent: cached model verdicts for request intent (ADR 0008).',
             "Keys are sha256(model + prompt + request text); values hold the model's answers only, never the text.",
             'Do not edit by hand; delete an entry to force a new call."""', "", "CACHE = {"]
    for k in sorted(cache):
        lines.append(f"    {k!r}: {cache[k]!r},")
    lines += ["}", ""]
    Path(path).write_text("\n".join(lines), encoding="utf-8")


def default_client():
    if not os.environ.get("OPENAI_API_KEY"):
        return None
    from openai import OpenAI
    return OpenAI()


class IntentClassifier:
    def __init__(self, client=None, cache=None, tracker=None, prompt=None):
        self.client, self.tracker = client, tracker
        self.cache = read_cache() if cache is None else cache
        self.prompt = prompt if prompt is not None else prompt_text()
        self.disagreements, self.new_entries = [], 0

    def _verdict(self, text):
        key = cache_key(text, self.prompt)
        hit = self.cache.get(key)
        if hit is not None:
            if self.tracker:
                self.tracker.record("openai", hit["model"], 0, 0, 0.0, cache_hit=True)
            return hit, True
        if self.client is None:
            return None, False
        t0 = time.perf_counter()
        resp = self.client.chat.completions.create(
            model=MODEL, messages=build_messages(text, self.prompt), seed=SEED, reasoning_effort="none",
            response_format={"type": "json_schema", "json_schema": SCHEMA}, store=False)
        ms = (time.perf_counter() - t0) * 1000
        answers = json.loads(resp.choices[0].message.content)
        entry = {"answers": answers, "label": label(answers), "model": MODEL}
        self.cache[key] = entry
        self.new_entries += 1
        if self.tracker:
            u = resp.usage
            self.tracker.record("openai", MODEL, u.prompt_tokens, u.completion_tokens, ms, cache_hit=False)
        return entry, False

    def prefetch(self, texts, workers=8):
        """Fill the cache for many texts with parallel live calls (cache misses only); results are order-free."""
        from concurrent.futures import ThreadPoolExecutor
        todo = sorted({t for t in texts if cache_key(t, self.prompt) not in self.cache})
        if self.client is None or not todo:
            return 0
        with ThreadPoolExecutor(max_workers=workers) as ex:
            list(ex.map(self._verdict, todo))
        return len(todo)

    def review(self, text):
        """Model verdict for any text, compared with the rules (records disagreements)."""
        v, _ = self._verdict(text)
        r = classify_rules(text)
        if v and v["label"] != r.label:
            self.disagreements.append({"text_sha256": hashlib.sha256(text.encode()).hexdigest()[:16], "rules": r.label,
                                       "model": v["label"], "rules_reason": r.reason, "model_rationale": v["answers"]["rationale"],
                                       "clarity": rules_clarity(text)})
        return v

    def classify(self, text):
        r = classify_rules(text)
        if rules_clarity(text) == "clear":
            return r
        v, cached = self._verdict(text)
        if v is None:
            return Intent(r.label, r.reason + "; no model verdict (no key, cache miss)", "rules (no model verdict)")
        return Intent(v["label"], v["answers"]["rationale"], "model (cache)" if cached else "model")

    def save(self, path=CACHE_PATH):
        if self.new_entries:
            write_cache(path, self.cache)
